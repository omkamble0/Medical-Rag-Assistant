"""
Clinical Disclaimer Engine for AegisMed Truth Engine.
Provides audience-tailored regulatory and clinical safety disclaimers
for Patient, Clinician, Low-Confidence, and Emergency acuity contexts.
"""

from typing import Dict
from enum import Enum


class DisclaimerMode(str, Enum):
    PATIENT = "patient"
    CLINICIAN = "clinician"
    EMERGENCY = "emergency"
    LOW_CONFIDENCE = "low_confidence"


PATIENT_DISCLAIMER = (
    "⚠️ MEDICAL INFORMATION NOTICE: This health summary is provided for educational and informational purposes only. "
    "It is not a substitute for professional medical advice, diagnosis, or individualized treatment. "
    "Always consult your primary physician or a qualified healthcare specialist regarding any medical condition or symptoms. "
    "If you are experiencing severe, worsening, or life-threatening symptoms, immediately dial emergency services (911 in the US/Canada, 999 in the UK, 112 in Europe) or go to the nearest emergency department."
)

CLINICIAN_DISCLAIMER = (
    "⚕️ CLINICAL DECISION SUPPORT NOTICE: This synthesis is generated by AegisMed Clinical Truth Engine for credentialed "
    "healthcare professionals. It summarizes peer-reviewed clinical guidelines, randomized controlled trials, and Oxford CEBM evidence. "
    "It does not replace independent clinical judgment, institutional hospital protocols, or direct patient evaluation. "
    "Prescribers remain solely responsible for verifying dosages, contraindications, renal adjustments, and drug-drug interactions before authorizing pharmacotherapy."
)

EMERGENCY_DISCLAIMER = (
    "🚨 CRITICAL CLINICAL ALERT: The symptoms described indicate potential high-acuity bodily distress requiring IMMEDIATE in-person emergency evaluation. "
    "DO NOT attempt to wait out these symptoms at home. "
    "Call 911 (or local emergency dispatch) immediately or proceed to the nearest Emergency Department. "
    "Do not drive yourself if you are feeling faint, dizzy, short of breath, or experiencing acute chest pressure."
)

LOW_CONFIDENCE_DISCLAIMER = (
    "ℹ️ CAUTIONARY EVIDENCE ADVISORY: The clinical evidence retrieved for this inquiry did not meet our high-certainty consensus threshold. "
    "The information provided is preliminary and non-definitive. "
    "Please provide additional clinical details (such as current medications, duration of symptoms, or lab values), "
    "or consult a clinical specialist for verified diagnosis."
)

DISCLAIMER_MAP: Dict[DisclaimerMode, str] = {
    DisclaimerMode.PATIENT: PATIENT_DISCLAIMER,
    DisclaimerMode.CLINICIAN: CLINICIAN_DISCLAIMER,
    DisclaimerMode.EMERGENCY: EMERGENCY_DISCLAIMER,
    DisclaimerMode.LOW_CONFIDENCE: LOW_CONFIDENCE_DISCLAIMER,
}


def get_disclaimer(mode: str) -> str:
    """Returns the tailored clinical disclaimer for the given audience mode."""
    m_clean = mode.strip().lower() if mode else "patient"
    if "emerg" in m_clean:
        return EMERGENCY_DISCLAIMER
    if "low" in m_clean or "uncertain" in m_clean:
        return LOW_CONFIDENCE_DISCLAIMER
    if "doc" in m_clean or "clinic" in m_clean:
        return CLINICIAN_DISCLAIMER
    return PATIENT_DISCLAIMER

